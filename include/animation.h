// animation.h - building blocks for time-based animation:
// interpolation and easing, keyframe tracks (tweening), sprite frame timing,
// delta-time movement and a frame clock.
#pragma once
#include "geometry.h"
#include <chrono>
#include <vector>

// ---- Interpolation
double lerp(double a, double b, double t);       // a + (b - a) * t
Point lerpPoint(Point a, Point b, double t);
double clamp01(double v);

// ---- Easing curves remap t in [0,1] so motion starts / stops gradually
// (the "ease in and ease out" principle of animation).
enum class Ease { Linear, In, Out, InOut };
double ease(Ease e, double t);
inline double easeInOut(double t) { return ease(Ease::InOut, t); }  // smoothstep 3t^2 - 2t^3
const char* easeName(Ease e);

// ---- Keyframes and tweening
// A keyframe stores the value of one property at one moment. Between two
// keyframes the in-betweens are generated by interpolating with a local
// parameter t = (time - k0.time) / (k1.time - k0.time), shaped by k0's easing.
struct Keyframe {
    double time;
    double value;
    Ease ease = Ease::InOut;  // easing of the segment that starts at this key
};

class KeyframeTrack {
public:
    KeyframeTrack& add(double time, double value, Ease e = Ease::InOut);  // keys must be added in time order
    double sample(double time) const;  // value at any time (clamped to the first / last key)
    double duration() const { return keys_.empty() ? 0 : keys_.back().time; }
    const std::vector<Keyframe>& keys() const { return keys_; }

private:
    std::vector<Keyframe> keys_;
};

// ---- Frame-based sprite animation runs on its OWN timer, so a walk cycle
// advances at e.g. 10 poses per second no matter how fast frames are rendered.
struct FrameAnimator {
    int frames = 1;
    double fps = 10;
    double accumulator = 0;
    int current = 0;
    void update(double dt);
};

// ---- Position-based animation: x_new = x_old + v * dt
struct Mover {
    Point pos, vel;  // pixels, pixels per second
    void update(double dt) {
        pos.x += vel.x * dt;
        pos.y += vel.y * dt;
    }
};

// ---- Measures the elapsed time (delta time) between frames.
class FrameClock {
public:
    FrameClock();
    double tick();                  // seconds since the previous tick
    double fps() const { return fps_; }  // smoothed frames per second for display

private:
    std::chrono::steady_clock::time_point last_;
    double fps_ = 0;
};
