int drawText(Framebuffer& fb, int x, int y, const std::string& text, Color c, int scale) {
    int penX = x;
    for (char ch : text) {
        if (ch == '\n') {
            penX = x;
            y += LINE_HEIGHT * scale;
            continue;
        }
        const Glyph* g = findGlyph(ch);
        for (int row = 0; row < GLYPH_H; ++row)
            for (int col = 0; col < GLYPH_W; ++col)
                if (g->rows[row][col] == '#')  // mask bit set: copy the pixel block
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx)
                            fb.setPixel(penX + col * scale + sx, y + row * scale + sy, c);
        penX += GLYPH_ADVANCE * scale;
    }
    return penX;
}

int drawTextShadow(Framebuffer& fb, int x, int y, const std::string& text, Color c, int scale,
                   Color shadow) {
    drawText(fb, x + scale, y + scale, text, shadow, scale);
    return drawText(fb, x, y, text, c, scale);
}

int textWidth(const std::string& text, int scale) {
    int best = 0, cur = 0;
    for (char ch : text) {
        if (ch == '\n') { best = cur > best ? cur : best; cur = 0; continue; }
        cur += GLYPH_ADVANCE * scale;
    }
    best = cur > best ? cur : best;
    return best > 0 ? best - scale : 0;  // no trailing gap after the last glyph
}

void drawTextCentered(Framebuffer& fb, int cx, int y, const std::string& text, Color c, int scale) {
    drawText(fb, cx - textWidth(text, scale) / 2, y, text, c, scale);
}
